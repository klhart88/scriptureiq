"""Builds supabase/seed.sql from supabase/plan_days.json (exported from the ScriptureIQ workbook)."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
P = json.loads((root / "supabase/plan_days.json").read_text())

def split_q2(q):
    qs = [m.end() for m in re.finditer(r"\?", q)]
    if len(qs) >= 2:
        cut = qs[-2]
        return q[:cut].strip(), q[cut:].strip()
    m = re.search(r";\s*(what does .*)$", q, re.I)
    if m:
        return q[:m.start()].strip() + "?", m.group(1)[0].upper() + m.group(1)[1:]
    return q.strip(), ""

def lit(v):
    if v is None or v == "":
        return "null"
    return "'" + str(v).replace("'", "''") + "'"

cols = ["day","reading","reading_code","psalm","psalm_code","section","book","video_title","video_url",
        "guide_title","guide_url","article_title","article_url","main_theme","primary_threads","supporting_threads",
        "pre_where","pre_watch","q1","q2_connect","q2_reveal","q3","practice","identity","q2_link"]
rows = []
for r in P:
    r = dict(r)
    r["q2_connect"], r["q2_reveal"] = split_q2(r["q2"])
    if not r.get("video_url"): r["video_title"] = None
    if not r.get("guide_url"): r["guide_title"] = None
    if not r.get("article_url"): r["article_title"] = None
    rows.append("(" + ",".join(str(r["day"]) if c == "day" else lit(r.get(c)) for c in cols) + ")")
assert len(rows) == 358
sql = ("-- Generated by scripts/build_seed.py. Do not edit by hand.\n"
       f"insert into public.plan_days ({','.join(cols)}) values\n" + ",\n".join(rows) +
       "\non conflict (day) do update set " + ",".join(f"{c}=excluded.{c}" for c in cols if c != "day") + ";\n")
(root / "supabase/seed.sql").write_text(sql)
print("wrote", len(rows), "days")
